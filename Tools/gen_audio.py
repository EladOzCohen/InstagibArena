"""Synthesizes every sound effect and music track of the game from scratch.

Nothing here is sampled or downloaded, so there are no licensing questions:
all of it is generated by this script and belongs to the project.
Pure Python (standard library only).

  python gen_audio.py [output_folder]

Writes  <output>/sfx/*.wav  (mono, so they can be spatialised in 3D)
and     <output>/music/*.wav (stereo, seamless loops).
"""

import array
import math
import os
import random
import sys
import wave

SR = 44100
TAU = 2.0 * math.pi
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "audio_out")


# --------------------------------------------------------------------- helpers

def mtof(midi):
    return 440.0 * 2.0 ** ((midi - 69) / 12.0)


def normalize(samples, peak=0.9):
    top = max(abs(x) for x in samples) or 1.0
    k = peak / top
    return [x * k for x in samples]


def write_wav(path, left, right=None):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    data = array.array("h")
    if right is None:
        data.extend(int(max(-1.0, min(1.0, x)) * 32767) for x in left)
        channels = 1
    else:
        for l, r in zip(left, right):
            data.append(int(max(-1.0, min(1.0, l)) * 32767))
            data.append(int(max(-1.0, min(1.0, r)) * 32767))
        channels = 2
    with wave.open(path, "wb") as w:
        w.setnchannels(channels)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(data.tobytes())
    seconds = len(left) / SR
    print("  %-34s %5.2f s" % (os.path.relpath(path, OUT), seconds))


def echo(samples, delay_s, feedback, taps=3):
    """Simple feedback delay that extends the sound by its tail."""
    d = int(delay_s * SR)
    out = samples + [0.0] * (d * taps)
    for i in range(len(samples)):
        for k in range(1, taps + 1):
            out[i + d * k] += samples[i] * (feedback ** k)
    return out


def saw(phase):
    return 2.0 * (phase - math.floor(phase + 0.5))


# --------------------------------------------------------------- sound effects

def footstep(seed, lp, thump_hz):
    rng = random.Random(seed)
    out, y = [], 0.0
    for i in range(int(0.15 * SR)):
        t = i / SR
        y += lp * (rng.uniform(-1, 1) - y)
        out.append(y * math.exp(-t * 36) * 1.6 + math.sin(TAU * thump_hz * t) * math.exp(-t * 45) * 0.7)
    return normalize(out, 0.8)


def land():
    rng = random.Random(7)
    out, y = [], 0.0
    for i in range(int(0.3 * SR)):
        t = i / SR
        y += 0.1 * (rng.uniform(-1, 1) - y)
        out.append(y * math.exp(-t * 16) * 1.5 + math.sin(TAU * 52 * t) * math.exp(-t * 14))
    return normalize(out, 0.9)


def jump(f0, f1, dur):
    rng = random.Random(11)
    out, phase, y = [], 0.0, 0.0
    n = int(dur * SR)
    for i in range(n):
        t = i / n
        f = f0 + (f1 - f0) * t
        phase += TAU * f / SR
        y += 0.2 * (rng.uniform(-1, 1) - y)
        env = math.sin(math.pi * t) ** 0.8
        out.append((math.sin(phase) * 0.7 + y * 0.3) * env)
    return normalize(out, 0.7)


def dodge():
    rng = random.Random(21)
    out, y1, y2 = [], 0.0, 0.0
    n = int(0.32 * SR)
    for i in range(n):
        t = i / n
        bell = math.sin(math.pi * t)
        a = 0.03 + 0.35 * bell
        y1 += a * (rng.uniform(-1, 1) - y1)
        y2 += 0.015 * (y1 - y2)
        out.append((y1 - y2) * bell ** 1.3)
    return normalize(out, 0.8)


def instagib_fire():
    rng = random.Random(31)
    n = int(0.55 * SR)
    out, phase, ring = [], 0.0, 0.0
    for i in range(n):
        t = i / SR
        f = 2400.0 * math.exp(-t * 11) + 140.0
        phase += TAU * f / SR
        body = (saw(phase / TAU) * 0.5 + math.tanh(3.0 * math.sin(phase)) * 0.5) * math.exp(-t * 7)
        crack = rng.uniform(-1, 1) * math.exp(-t * 130)
        thump = math.sin(TAU * 68 * t) * math.exp(-t * 15) * 0.9
        ring = (math.sin(TAU * 880 * t + 3.0 * math.sin(TAU * 6 * t)) * math.exp(-t * 5) * 0.16
                + math.sin(TAU * 1320 * t) * math.exp(-t * 6) * 0.1)
        out.append(body * 0.7 + crack * 0.9 + thump + ring)
    out = echo(out, 0.105, 0.32, 4)
    return normalize(out, 0.9)


def ping(freq, dur, decay):
    return [math.sin(TAU * freq * (i / SR)) * math.exp(-(i / SR) * decay) for i in range(int(dur * SR))]


def mix_at(parts):
    """parts: list of (start_seconds, samples, gain)."""
    n = max(int(s * SR) + len(x) for s, x, g in parts)
    out = [0.0] * n
    for s, x, g in parts:
        o = int(s * SR)
        for i, v in enumerate(x):
            out[o + i] += v * g
    return out


def hit_confirm():
    return normalize(mix_at([(0.0, ping(1568, 0.2, 22), 1.0), (0.0, ping(2349, 0.2, 28), 0.5)]), 0.8)


def kill_confirm():
    low = [math.sin(TAU * 90 * (i / SR)) * math.exp(-(i / SR) * 12) for i in range(int(0.3 * SR))]
    return normalize(mix_at([
        (0.00, ping(988, 0.3, 14), 0.8), (0.07, ping(1318, 0.3, 14), 0.8),
        (0.14, ping(1976, 0.45, 10), 1.0), (0.0, low, 0.9)]), 0.9)


def death():
    rng = random.Random(41)
    out, phase, y = [], 0.0, 0.0
    for i in range(int(0.75 * SR)):
        t = i / SR
        phase += TAU * (520.0 * math.exp(-t * 4.5) + 45.0) / SR
        y += 0.15 * (rng.uniform(-1, 1) - y)
        out.append(math.sin(phase) * math.exp(-t * 4.5) * 0.8 + y * math.exp(-t * 9) * 0.9)
    return normalize(out, 0.9)


def spawn():
    out = []
    n = int(0.8 * SR)
    for i in range(n):
        t = i / n
        s = 0.0
        for k, f in enumerate((440.0, 660.0, 880.0, 1320.0)):
            vib = 1.0 + 0.01 * math.sin(TAU * (5 + k) * t * 0.8)
            s += math.sin(TAU * f * vib * (i / SR)) * (0.5 / (k + 1))
        out.append(s * math.sin(math.pi * t) ** 1.5)
    return normalize(out, 0.7)


def ui_click():
    return normalize([
        math.sin(TAU * 1400 * (i / SR)) * math.exp(-(i / SR) * 60)
        + 0.5 * math.sin(TAU * 700 * (i / SR)) * math.exp(-(i / SR) * 50)
        for i in range(int(0.08 * SR))], 0.6)


def ui_start():
    return normalize(mix_at([(0.0, ping(660, 0.35, 8), 0.8), (0.10, ping(990, 0.4, 7), 1.0),
                             (0.0, ping(330, 0.35, 8), 0.4)]), 0.8)


def match_start():
    def note(f):
        out, phase, y = [], 0.0, 0.0
        for i in range(int(0.45 * SR)):
            t = i / SR
            phase += f / SR
            y += 0.12 * (saw(phase) - y)
            out.append(y * math.exp(-t * 5) * min(1.0, t / 0.005))
        return out
    return normalize(mix_at([(0.0, note(392), 1.0), (0.14, note(523), 1.0), (0.28, note(784), 1.2)]), 0.8)


def match_end():
    n = int(3.2 * SR)
    out = [0.0] * n
    for ratio, amp, dec in ((1.0, 1.0, 1.2), (2.01, 0.6, 1.6), (2.76, 0.4, 2.2), (5.4, 0.25, 3.2), (8.9, 0.15, 4.5)):
        f = 220.0 * ratio
        for i in range(n):
            t = i / SR
            out[i] += math.sin(TAU * f * t) * amp * math.exp(-t * dec)
    return normalize(out, 0.85)


# ------------------------------------------------------------------------ music

class Mix:
    """Two buses (center and wide). Writes wrap around so the loop is seamless."""

    def __init__(self, n):
        self.n = n
        self.center = [0.0] * n
        self.wide = [0.0] * n

    def add(self, bus, start, samples, gain):
        buf = self.center if bus == "c" else self.wide
        n = self.n
        for i, s in enumerate(samples):
            buf[(start + i) % n] += s * gain


def kick_sample():
    out, phase = [], 0.0
    for i in range(int(0.32 * SR)):
        t = i / SR
        phase += TAU * (45.0 + 110.0 * math.exp(-t * 30)) / SR
        out.append(math.sin(phase) * math.exp(-t * 9) + (0.4 if i < 40 else 0.0) * math.exp(-i / 10.0))
    return out


def snare_sample():
    rng = random.Random(5)
    return [rng.uniform(-1, 1) * math.exp(-(i / SR) * 17) * 0.7
            + math.sin(TAU * 185 * (i / SR)) * math.exp(-(i / SR) * 24) * 0.5
            for i in range(int(0.26 * SR))]


def hat_sample(decay):
    rng = random.Random(9)
    prev, out = 0.0, []
    for i in range(int((0.35 if decay < 40 else 0.12) * SR)):
        x = rng.uniform(-1, 1)
        out.append((x - prev) * math.exp(-(i / SR) * decay))
        prev = x
    return out


def bass_note(freq, dur):
    out, y, phase = [], 0.0, 0.0
    for i in range(int(dur * SR)):
        t = i / SR
        phase += freq / SR
        cutoff = 0.05 + 0.25 * math.exp(-t * 14)
        y += cutoff * (saw(phase) - y)
        out.append(y * min(1.0, t / 0.004) * math.exp(-t * 3.2) * 1.6)
    return out


def arp_note(freq, dur):
    out, y, phase = [], 0.0, 0.0
    for i in range(int(dur * SR)):
        t = i / SR
        phase += freq / SR
        pulse = 1.0 if (phase % 1.0) < 0.3 else -1.0
        y += 0.35 * (pulse - y)
        out.append(y * min(1.0, t / 0.003) * math.exp(-t * 11))
    return out


def pad_chord(freqs, dur):
    n = int(dur * SR)
    out = [0.0] * n
    for f in freqs:
        for detune in (0.994, 1.0, 1.006):
            phase, y = 0.37, 0.0
            step = f * detune / SR
            for i in range(n):
                phase += step
                y += 0.06 * (saw(phase) - y)
                out[i] += y
    atk, rel = int(0.35 * SR), int(0.45 * SR)
    for i in range(n):
        g = min(1.0, i / atk, (n - i) / rel)
        out[i] *= g * 0.18
    return out


def lead_note(freq, dur):
    out, phase, y = [], 0.0, 0.0
    n = int(dur * SR)
    for i in range(n):
        t = i / SR
        vib = 1.0 + (0.006 * math.sin(TAU * 5.5 * t) if t > 0.12 else 0.0)
        phase += freq * vib / SR
        y += 0.3 * (saw(phase) * 0.5 + math.sin(TAU * phase) * 0.8 - y)
        env = min(1.0, t / 0.01) * min(1.0, (n - i) / (0.06 * SR))
        out.append(y * env)
    return out


class Cache:
    def __init__(self):
        self.d = {}

    def get(self, key, make):
        if key not in self.d:
            self.d[key] = make()
        return self.d[key]


SONGS = {
    # Am - F - C - G
    "battle_01": dict(bpm=140, bars=32, prog=[(45, True), (41, False), (48, False), (43, False)],
                      bass=[0, 0, 12, 0, 0, 12, 7, 0], kicks=[0, 4, 8, 10, 12], snare=[4, 12],
                      arp=[0, 1, 2, 3, 2, 1, 2, 4], drums=True, pad=True, seed=1),
    # Dm - Bb - F - C
    "battle_02": dict(bpm=150, bars=32, prog=[(50, True), (46, False), (41, False), (48, False)],
                      bass=[0, 12, 0, 12, 0, 7, 0, 12], kicks=[0, 3, 6, 8, 11, 14], snare=[4, 12],
                      arp=[0, 2, 1, 3, 2, 4, 3, 5], drums=True, pad=True, seed=2),
    # Am - F - C - Em, slow and atmospheric
    "menu_theme": dict(bpm=88, bars=16, prog=[(45, True), (41, False), (48, False), (40, True)],
                       bass=[0, None, None, None, 7, None, None, None], kicks=[0, 8], snare=[],
                       arp=[0, 1, 2, 1, 3, 2, 1, 2], drums=False, pad=True, seed=3),
}


def render_song(name, spec):
    rng = random.Random(spec["seed"])
    cache = Cache()
    step = int(60.0 / spec["bpm"] / 4.0 * SR)
    bar = step * 16
    total = bar * spec["bars"]
    mix = Mix(total)
    kick, snare = kick_sample(), snare_sample()
    hat_c, hat_o = hat_sample(80.0), hat_sample(25.0)
    menu = not spec["drums"]
    arp_seq = spec["arp"]

    for b in range(spec["bars"]):
        root, minor = spec["prog"][b % len(spec["prog"])]
        third = root + (3 if minor else 4)
        fifth = root + 7
        tones = [root + 12, third + 12, fifth + 12, root + 24, third + 24, fifth + 24]
        start = b * bar
        section_b = (b % 16) >= 8   # second half of every 16 bars is the full version

        # pad
        if spec["pad"]:
            chord = cache.get(("pad", root, minor), lambda: pad_chord(
                [mtof(root + 12), mtof(third + 12), mtof(fifth + 12)], (bar + 2200) / SR))
            if menu or section_b:
                mix.add("w", start, chord, 1.0 if not menu else 1.3)

        # bass
        if not menu or b >= 4:
            for i, off in enumerate(spec["bass"]):
                if off is None:
                    continue
                dur = (1.7 if not menu else 6.0) * step
                note = cache.get(("bass", root + off, round(dur)), lambda: bass_note(mtof(root + off), dur / SR))
                mix.add("c", start + i * 2 * step, note, 0.5 if not menu else 0.38)

        # drums
        if spec["drums"]:
            for k in spec["kicks"]:
                mix.add("c", start + k * step, kick, 0.9)
            for s in spec["snare"]:
                mix.add("c", start + s * step, snare, 0.55)
            for i in range(16):
                if i % 4 == 2:
                    mix.add("w", start + i * step, hat_o, 0.16)
                elif i % 2 == 0 and (section_b or b >= 16):
                    mix.add("w", start + i * step, hat_c, 0.1)
                elif b >= 24:
                    mix.add("w", start + i * step, hat_c, 0.05)
        elif b >= 8:
            for k in spec["kicks"]:
                mix.add("c", start + k * step, kick, 0.35)

        # arpeggio
        if not menu or b >= 2:
            for i in range(16 if not menu else 8):
                idx = arp_seq[i % len(arp_seq)] + (2 if (b % 8) >= 4 and not menu else 0)
                idx = min(idx, len(tones) - 1)
                s = i * step * (1 if not menu else 2)
                note = cache.get(("arp", tones[idx], step), lambda: arp_note(mtof(tones[idx]), 1.5 * step / SR))
                mix.add("w", start + s, note, 0.2 if not menu else 0.16)

        # lead
        if section_b and (not menu or b >= 8):
            pos = 0
            while pos < 16:
                length = rng.choice([2, 2, 4, 4, 6])
                length = min(length, 16 - pos)
                if rng.random() < 0.8:
                    midi = tones[rng.choice([2, 3, 4, 4, 5])] + 12
                    dur = length * step * (0.9 if not menu else 1.6)
                    note = cache.get(("lead", midi, round(dur)), lambda: lead_note(mtof(midi), dur / SR))
                    mix.add("c", start + pos * step, note, 0.22 if not menu else 0.17)
                pos += length

    # Stereo: the wide bus arrives slightly later on the right.
    delay = int(0.016 * SR)
    left = [mix.center[i] + mix.wide[i] for i in range(total)]
    right = [mix.center[i] + mix.wide[(i - delay) % total] for i in range(total)]
    peak = max(max(abs(x) for x in left), max(abs(x) for x in right)) or 1.0
    k = 0.85 / peak
    left = [math.tanh(x * k * 1.15) / math.tanh(1.15) for x in left]
    right = [math.tanh(x * k * 1.15) / math.tanh(1.15) for x in right]
    write_wav(os.path.join(OUT, "music", "%s.wav" % name), left, right)


# ---- MAPS: jump pad whoosh (added at the end of the effects)
def jump_pad():
    rng = random.Random(77)
    n = int(0.55 * SR)
    out, phase, y1, y2 = [], 0.0, 0.0, 0.0
    for i in range(n):
        t = i / n
        f = 160.0 + 900.0 * t * t
        phase += TAU * f / SR
        y1 += (0.05 + 0.4 * t) * (rng.uniform(-1, 1) - y1)
        y2 += 0.02 * (y1 - y2)
        env = math.sin(math.pi * min(1.0, t * 1.15)) ** 0.7 * (1.0 - t) ** 0.4
        out.append(((y1 - y2) * 1.4 + math.sin(phase) * 0.45 + math.sin(phase * 2.0) * 0.12) * env)
    return normalize(out, 0.8)


# ------------------------------------------------------------------------- main

def main():
    print("Writing audio to", OUT)
    sfx = {
        "footstep_01": footstep(1, 0.30, 90),
        "footstep_02": footstep(2, 0.24, 80),
        "footstep_03": footstep(3, 0.34, 100),
        "footstep_04": footstep(4, 0.27, 85),
        "land": land(),
        "jump": jump(200, 480, 0.16),
        "double_jump": jump(340, 820, 0.18),
        "dodge": dodge(),
        "instagib_fire": instagib_fire(),
        "hit_confirm": hit_confirm(),
        "kill_confirm": kill_confirm(),
        "death": death(),
        "spawn": spawn(),
        "ui_click": ui_click(),
        "ui_start": ui_start(),
        "match_start": match_start(),
        "match_end": match_end(),
        "jump_pad": jump_pad(),   # MAPS
    }
    print("Sound effects:")
    for name, samples in sfx.items():
        write_wav(os.path.join(OUT, "sfx", name + ".wav"), samples)

    print("Music:")
    for name, spec in SONGS.items():
        render_song(name, spec)
    print("Done.")


if __name__ == "__main__":
    main()
